const { _electron: electron } = require('playwright');
const path = require('path');
const root = path.join(__dirname, '..');
const out = path.join(__dirname, 'out');
(async () => {
  const app = await electron.launch({ executablePath: require(path.join(root, 'node_modules', 'electron')), args: ['--no-sandbox', root, path.join(out, 'work.pdf')] });
  const win = await app.firstWindow();
  const errors = [];
  win.on('pageerror', (e) => errors.push(e.message));
  win.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  await win.waitForFunction(() => document.querySelector('.page canvas.pc'), null, { timeout: 20000 });
  await win.waitForTimeout(400);
  const h = () => win.evaluate(() => ({ ribbon: document.querySelector('#ribbon').offsetHeight, viewerTop: document.querySelector('#viewer').getBoundingClientRect().top, scale: window.__pdfacil.S.scale.toFixed(3) }));
  console.log('home:', JSON.stringify(await h()));
  await win.screenshot({ path: path.join(out, '16-home-compact.png'), clip: { x: 0, y: 0, width: 1300, height: 200 } });
  await win.click('.tab[data-tab=comment]');
  console.log('comment:', JSON.stringify(await h()));
  await win.click('.tab[data-tab=home]');
  await win.click('#ribbonToggle');
  await win.waitForTimeout(200);
  console.log('collapsed:', JSON.stringify(await h()));
  await win.screenshot({ path: path.join(out, '17-collapsed.png'), clip: { x: 0, y: 0, width: 1300, height: 200 } });
  await win.click('.tab[data-tab=comment]');
  await win.waitForTimeout(150);
  console.log('peek visible:', await win.evaluate(() => document.body.classList.contains('ribbon-peek')), JSON.stringify(await h()));
  await win.screenshot({ path: path.join(out, '18-peek.png'), clip: { x: 0, y: 0, width: 1300, height: 260 } });
  await win.click('.panel.active [data-tool=highlight]');
  await win.waitForTimeout(100);
  console.log('after tool click peek:', await win.evaluate(() => document.body.classList.contains('ribbon-peek')), 'tool:', await win.evaluate(() => window.__pdfacil.S.tool));
  await win.click('#viewer', { position: { x: 5, y: 5 } });
  await win.keyboard.press('Control+F1');
  await win.waitForTimeout(200);
  console.log('expanded again:', JSON.stringify(await h()));
  console.log('ERRORS:', errors.join('\n'));
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].destroy());
})().catch((e) => { console.error('FAIL', e); process.exit(1); });
