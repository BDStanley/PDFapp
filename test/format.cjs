const { _electron: electron } = require('playwright');
const path = require('path');
const root = path.join(__dirname, '..');
const out = path.join(__dirname, 'out');
(async () => {
  const app = await electron.launch({ executablePath: require(path.join(root, 'node_modules', 'electron')), args: ['--no-sandbox', root, path.join(out, 'fmt.pdf')] });
  const win = await app.firstWindow();
  const errors = [];
  win.on('pageerror', (e) => errors.push(e.message));
  win.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  await win.waitForFunction(() => document.querySelector('.page canvas.pc'), null, { timeout: 20000 });
  const pg = await (await win.$('.page[data-idx="0"]')).boundingBox();
  await win.click('.panel.active [data-tool=text]');
  await win.mouse.click(pg.x + 120, pg.y + 120);
  await win.keyboard.type('Formatted note: this one should be Times, 18pt, red.');
  await win.keyboard.press('Escape');
  await win.click('.panel.active [data-tool=select]');
  const tb = await win.$('.ann-text .tb');
  const bb = await tb.boundingBox();
  await win.mouse.click(bb.x + 20, bb.y + 8, { button: 'right' });
  await win.waitForTimeout(200);
  await win.screenshot({ path: path.join(out, '14-menu.png') });
  await win.selectOption('#ctxMenu .fmt-font', 'times');
  await win.selectOption('#ctxMenu .fmt-size', '18');
  await win.click('#ctxMenu .fmt-colors .swatch[title=Red]');
  await win.click('#ctxMenu .fmt-step[data-d="1"]');
  await win.click('#ctxMenu .fmt-step[data-d="-1"]');
  console.log('menu still open:', await win.$eval('#ctxMenu', (m) => !m.hidden));
  const a = await win.evaluate(() => window.__pdfapp.S.model.pages[0].annots[0]);
  console.log('annot:', JSON.stringify({ font: a.font, size: a.size, color: a.color, h: a.h.toFixed(1) }));
  await win.screenshot({ path: path.join(out, '15-menu-after.png') });
  await win.keyboard.press('Escape');
  await win.mouse.click(pg.x + 5, pg.y + 5);
  await win.keyboard.press('Control+z');
  console.log('after undo size:', await win.evaluate(() => window.__pdfapp.S.model.pages[0].annots[0].size));
  await win.keyboard.press('Control+y');
  await win.keyboard.press('Control+s');
  await win.waitForTimeout(1500);
  console.log('ERRORS:', errors.join('\n'));
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].destroy());
})().catch((e) => { console.error('FAIL', e); process.exit(1); });
